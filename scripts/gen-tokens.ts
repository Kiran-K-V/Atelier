import { writeFileSync } from 'node:fs'
import { cssBezier, duration, ease, font, fontSize, palette, radius, shadow } from '../src/design/tokens.ts'

const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
const colorVars = (theme: keyof typeof palette) =>
  Object.entries(palette[theme])
    .map(([k, v]) => `  --color-${kebab(k)}: ${v};`)
    .join('\n')

const themeBlock = [
  ...Object.keys(palette.dark).map((k) => `  --color-${kebab(k)}: var(--c-${kebab(k)});`),
  ...Object.entries(font).map(([k, v]) => `  --font-${k}: ${v};`),
  ...Object.entries(fontSize).map(([k, v]) => `  --text-${k}: ${v};`),
  ...Object.entries(radius).map(([k, v]) => `  --radius-${k}: ${v};`),
  ...Object.entries(shadow).map(([k, v]) => `  --shadow-${k}: ${v};`),
  ...Object.entries(duration).map(([k, v]) => `  --duration-${k}: ${v}ms;`),
  ...(Object.keys(ease) as (keyof typeof ease)[]).map((k) => `  --ease-${k}: ${cssBezier(k)};`),
].join('\n')

const rawVars = (theme: keyof typeof palette) => colorVars(theme).replaceAll('--color-', '--c-')

const css = `/* Generated by scripts/gen-tokens.ts from src/design/tokens.ts. Do not edit. */
@theme inline {
${themeBlock}
}

:root, :root[data-theme='dark'] {
  color-scheme: dark;
${rawVars('dark')}
}

@media (prefers-color-scheme: light) {
  :root:not([data-theme='dark']) {
    color-scheme: light;
${rawVars('light')}
  }
}

:root[data-theme='light'] {
  color-scheme: light;
${rawVars('light')}
}
`

writeFileSync(new URL('../src/design/tokens.css', import.meta.url), css)
